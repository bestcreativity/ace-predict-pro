-- Today / Tomorrow restructure: 5 matches per day, 3 tips per match.
-- Replaces the old 5-slot model (ace_prediction_slots).
-- ─────────────────────────────────────────────────────────────────────────────

-- 1. Remove the old cron jobs.
select cron.unschedule(jobid)
from cron.job
where jobname in ('ace-daily-predictions', 'ace-clear-daily-predictions');

-- 2. Drop old functions that reference the old tables.
drop function if exists public.manage_ace_prediction_slot(
  text, smallint, boolean, text, text, text, text, text, text, smallint, text, text, text
);
drop function if exists public.ace_archive_game_history();
drop function if exists public.ace_set_game_result(text, date, smallint, text);
drop function if exists public.ace_get_game_history(integer);

-- 3. Drop old tables.
drop table if exists public.ace_game_history;
drop table if exists public.ace_prediction_slots;

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Live matches, keyed by (match_date, slot).
-- ─────────────────────────────────────────────────────────────────────────────
create table public.ace_matches (
  id               bigint generated by default as identity primary key,
  match_date       date        not null,
  slot             smallint    not null check (slot between 1 and 5),
  published        boolean     not null default false,
  team_a           text        not null default '',
  team_b           text        not null default '',
  league           text        not null default '',
  kickoff          text        not null default '',
  tip_over25       text        not null default '',
  tip_halffull     text        not null default '',
  tip_highest_half text        not null default '',
  slip_image       text,
  ad_zone_id       text        not null default '',
  ad_url           text        not null default '',
  source           text        not null default 'manual',
  source_fixture_id bigint,
  generated_at     timestamptz,
  updated_at       timestamptz not null default now(),
  unique (match_date, slot)
);

alter table public.ace_matches enable row level security;

create policy "Anyone can read ACE matches"
  on public.ace_matches for select to anon, authenticated using (true);

grant select on public.ace_matches to anon, authenticated;
revoke insert, update, delete on public.ace_matches from anon, authenticated;

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Archived matches for the weekly tracker (one result per match).
-- ─────────────────────────────────────────────────────────────────────────────
create table public.ace_game_history (
  id               bigint generated by default as identity primary key,
  match_date       date        not null,
  slot             smallint    not null check (slot between 1 and 5),
  team_a           text        not null,
  team_b           text        not null,
  league           text        not null,
  kickoff          text        not null,
  tip_over25       text        not null default '',
  tip_halffull     text        not null default '',
  tip_highest_half text        not null default '',
  result           text        not null default 'pending'
                     check (result in ('pending', 'win', 'loss')),
  created_at       timestamptz not null default now(),
  unique (match_date, slot)
