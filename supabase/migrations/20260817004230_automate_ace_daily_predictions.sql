create table if not exists public.ace_automation_runs (
  id bigint generated by default as identity primary key,
  run_date date not null,
  status text not null check (status in ('running', 'completed', 'failed')),
  selected_count smallint not null default 0,
  api_requests smallint not null default 0,
  message text not null default '',
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

alter table public.ace_automation_runs enable row level security;
revoke all on public.ace_automation_runs from anon, authenticated;

create or replace function public.get_ace_automation_secrets(p_cron_secret text)
returns table(api_football_key text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expected text;
begin
  select decrypted_secret
  into v_expected
  from vault.decrypted_secrets
  where name = 'ace_automation_cron_secret'
  limit 1;

  if v_expected is null or p_cron_secret is distinct from v_expected then
    raise exception 'Invalid automation secret' using errcode = '28000';
  end if;

  return query
  select decrypted_secret
  from vault.decrypted_secrets
  where name = 'ace_api_football_key'
  limit 1;
end;
$$;

revoke all on function public.get_ace_automation_secrets(text) from public;
grant execute on function public.get_ace_automation_secrets(text) to service_role;

